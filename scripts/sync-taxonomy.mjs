// Copies src/taxonomy.js to supabase/functions/_shared/taxonomy.js so the
// scan-card edge function uses the same standard value lists as the web app.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(root, 'src/taxonomy.js');
const dest = resolve(root, 'supabase/functions/_shared/taxonomy.js');
mkdirSync(dirname(dest), { recursive: true });
const banner = '// GENERATED by scripts/sync-taxonomy.mjs from src/taxonomy.js. Do not edit here.\n';
writeFileSync(dest, banner + readFileSync(src, 'utf8'));
console.log('taxonomy synced ->', dest.replace(root + '/', ''));
